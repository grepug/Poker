export const FALLBACK_PLAYER_EMOJI = "😀";

export function getRandomPlayerEmoji(excludeEmoji?: string): string {
  const pool = excludeEmoji
    ? PLAYER_EMOJI_OPTIONS.filter((emoji) => emoji !== excludeEmoji)
    : PLAYER_EMOJI_OPTIONS;
  const source = pool.length > 0 ? pool : PLAYER_EMOJI_OPTIONS;
  const randomIndex = Math.floor(Math.random() * source.length);
  return source[randomIndex] ?? FALLBACK_PLAYER_EMOJI;
}
